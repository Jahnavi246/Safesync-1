def generate_voice_audio(text, lang_code):
    """Generates audio bytes using gTTS for dynamic voice responses."""
    if not GTTS_AVAIL:
        return None
    try:
        tts = gTTS(text=text, lang=lang_code, slow=False)
        fp = io.BytesIO()
        tts.write_to_fp(fp)
        fp.seek(0)
        return fp
    except Exception:
        return None

