from streamlit_js_eval import get_geolocation


def get_live_user_location():
  """Fetches real-time HTML5 browser GPS coordinates."""
  loc_data = get_geolocation()
  if loc_data and "coords" in loc_data:
    lat = loc_data["coords"]["latitude"]
    lon = loc_data["coords"]["longitude"]
    return round(lat, 4), round(lon, 4), True
  return 17.3850, 78.4867, False


def get_coordinates(location_name):
  if not GEOPY_AVAIL or not location_name.strip():
    return 17.3850, 78.4867
  try:
    query = (
        location_name if "India" in location_name else f"{location_name}, India"
    )
    geolocator = Nominatim(user_agent="safesync_disaster_app_v8", timeout=5)
    loc = geolocator.geocode(query)
    if loc:
      return round(loc.latitude, 4), round(loc.longitude, 4)
  except Exception:
    pass
  return 17.3850, 78.4867

@st.cache_data(ttl=600)
def fetch_live_telemetry(lat, lon, hazard="Landslide", vuln="Low"):
    """Fetches accurate real-time weather metrics from Open-Meteo API and calculates risk via rules.py."""
    url = f"https://api.open-meteo.com/v1/forecast?latitude={lat}&longitude={lon}&current=temperature_2m,relative_humidity_2m,rain,showers,precipitation,wind_speed_10m&daily=precipitation_sum&timezone=auto"
    try:
        response = requests.get(url, timeout=5)
        response.raise_for_status()
        data_json = response.json()
        current = data_json.get("current", {})
        daily = data_json.get("daily", {})

        temp = round(current.get("temperature_2m", 25.0), 1)
        wind = round(current.get("wind_speed_10m", 0.0), 1)
        
        # Calculate precipitation
        current_precip = current.get("precipitation", current.get("rain", 0.0))
        daily_precip_list = daily.get("precipitation_sum", [])
        daily_precip = daily_precip_list[0] if daily_precip_list else 0.0
        
        # Select highest value between active rainfall and forecasted daily rainfall
        rain = round(max(current_precip, daily_precip), 1)

        # Build telemetry dictionary for rules.py integration
        telemetry_payload = {
            "rain_mm": rain,
            "wind_speed": wind,
            "imd_alert": "GREEN"
        }
        
        if rain > 50 or wind > 60:
            telemetry_payload["imd_alert"] = "RED"
        elif rain > 15 or wind > 30:
            telemetry_payload["imd_alert"] = "ORANGE"
        elif rain > 5 or wind > 15:
            telemetry_payload["imd_alert"] = "YELLOW"

        # Evaluate risk score and relocation zone using rules.py logic
        calculated_score = rules.evaluate_risk_score(hazard, telemetry_payload, vulnerability_level=vuln)
        reloc_priority, risk_zone, _ = rules.determine_relocation_priority(calculated_score)

        return {
            "temp": temp,
            "wind_speed": wind,
            "rain_mm": rain,
            "imd_alert": f"{telemetry_payload['imd_alert']} ALERT Watch",
            "ndma_alert": f"NDMA SACHET: Dynamic Risk Level {calculated_score}/100",
            "severity": risk_zone,
            "risk_score": calculated_score,
            "relocation_priority": reloc_priority
        }
    except Exception:
        return {
            "temp": 0.0,
            "wind_speed": 0.0,
            "rain_mm": 0.0,
            "imd_alert": "Offline / Connection Error",
            "ndma_alert": "NDMA SACHET: System Unavailable",
            "severity": "Green Zone",
            "risk_score": 15,
            "relocation_priority": "Low Risk / Monitor"
        }

